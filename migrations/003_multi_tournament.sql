-- Multiple tournaments, simpler formats (knockout is played in the eFootball app),
-- league legs, tournament details for the registration page, readable player IDs
-- and a readable activity log. Existing data is preserved.

-- Tournament details ------------------------------------------------------------
alter table tournament add column if not exists created_at timestamptz not null default now();
alter table tournament alter column starts_on drop not null;
alter table tournament add column if not exists registration_closes timestamptz;
alter table tournament add column if not exists entry_fee integer;
alter table tournament add column if not exists prize text;
alter table tournament add column if not exists description text;
alter table tournament add column if not exists knockout boolean not null default false;
alter table tournament add column if not exists legs integer not null default 1;

-- Formats: 'league' (knockout on/off) or 'knockout' (knockout only, played in the app).
alter table tournament drop constraint if exists tournament_format_check;
alter table tournament alter column format set default 'league';
update tournament set format = 'league', knockout = true where format = 'league_knockout';
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'tournament_format_v2') then
    alter table tournament add constraint tournament_format_v2 check (format in ('league', 'knockout'));
    alter table tournament add constraint tournament_legs_check check (legs in (1, 2));
    alter table tournament add constraint tournament_fee_check check (entry_fee is null or entry_fee >= 0);
  end if;
end $$;

-- Home & away leagues meet each pair twice (once each way): uniqueness is per ordered pair.
drop index if exists league_pair;
create unique index if not exists league_pair_ordered on fixture(tournament_id, home, away) where stage = 'league';

-- Readable player IDs (XG-0001 …), assigned to existing players too.
alter table player add column if not exists public_no integer generated by default as identity;
create unique index if not exists player_public_no on player(public_no);

-- Readable activity log.
alter table audit_event add column if not exists actor_name text;
alter table audit_event add column if not exists actor_role text;
alter table audit_event add column if not exists tournament_id text;
alter table audit_event add column if not exists summary text;
alter table audit_event add column if not exists affected text;

-- Coordinators now cover every tournament ('*').
update coordinator set tournaments = array['*'] where not ('*' = any(tournaments));
